    opts = {
      -- make sure mason installs the server
      servers = {
        ---@type lspconfig.options.tsserver
        tsserver = {
          enabled = false, -- only use typescript tools
          keys = {
            {
              "<leader>co",
              "<cmd>TSToolsOrganizeImports<cr>",
              desc = "Organize Imports",
            },
            {
              "<leader>cR",
              "<cmd>TSToolsRemoveUnusedImports<cr>",
